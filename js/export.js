// Export a solved coil plane to the supported interchange formats.
//
// Formats
// -------
//  * .mcfunction : /setblock commands (works in vanilla 1.12.2 and on the
//                  client via a function or command block chain).
//  * .nbt        : vanilla Structure Block template (gzipped NBT), placed with
//                  a structure block from <world>/generated/<ns>/structure/.
//  * .snbt       : Building Gadgets 1.12.2 template, i.e. the NBT string the
//                  Template Manager puts on / reads from the system clipboard.
//                  Copy it to the clipboard and press "Paste" in the Template
//                  Manager GUI.
(function (root) {
  'use strict';

  var Opt = (typeof require !== 'undefined' && typeof module !== 'undefined')
    ? require('./optimizer.js')
    : root.TurbineOpt;
  var Nbt = (typeof require !== 'undefined' && typeof module !== 'undefined')
    ? require('./nbt.js')
    : root.TurbineNbt;
  var EMPTY = -1, CONNECTOR = -2, BEARING = -3, RESERVED = -4;

  // Metadata for the six built-in NuclearCraft coils.  Every addon coil is a
  // separate block with metadata 0.
  var BASE_META = {
    magnesium: 0, beryllium: 1, aluminum: 2, gold: 3, copper: 4, silver: 5
  };

  function coilBlock(def) {
    var m = BASE_META[def.id];
    if (m != null) {
      return { Name: 'nuclearcraft:turbine_dynamo_coil', Properties: { type: def.id }, meta: m };
    }
    return { Name: 'nuclearcraft:turbine_dynamo_coil_' + def.id };
  }
  function casingBlock() { return { Name: 'nuclearcraft:turbine_casing', Properties: { frame: 'false' } }; }
  function glassBlock() { return { Name: 'nuclearcraft:turbine_glass' }; }
  function bearingBlock() { return { Name: 'nuclearcraft:turbine_rotor_bearing' }; }
  function connectorBlock() { return { Name: 'nuclearcraft:turbine_coil_connector' }; }
  function airBlock() { return { Name: 'minecraft:air' }; }

  // Build the list of placed blocks for the plane.  Grid row 0 is the bottom
  // row, so the plane is vertical (X = column, Y = row, Z = layer).
  // `fill` selects the block used for the unused wall cells: 'casing' or 'glass'.
  function buildItems(N, kind, labels, defs, origin, fill) {
    origin = origin || [0, 0, 0];
    var wall = fill === 'glass' ? glassBlock() : casingBlock();
    var items = [];
    for (var r = 0; r < N; r++) {
      for (var c = 0; c < N; c++) {
        var i = r * N + c, k = kind[i], lab = labels[i];
        var pos = [origin[0] + c, origin[1] + r, origin[2]];
        var block, slotKind;
        if (k === BEARING) { block = bearingBlock(); slotKind = 'bearing'; }
        else if (k === RESERVED || lab === RESERVED) { block = airBlock(); slotKind = 'air'; }
        else if (lab >= 0) { block = coilBlock(defs[lab]); slotKind = 'coil'; }
        else if (lab === CONNECTOR) { block = connectorBlock(); slotKind = 'connector'; }
        else { block = wall; slotKind = fill === 'glass' ? 'glass' : 'casing'; }
        items.push({ pos: pos, block: block, kind: slotKind });
      }
    }
    return items;
  }

  // --- .mcfunction --------------------------------------------------------
  function toMcFunction(N, kind, labels, defs, opts) {
    opts = opts || {};
    var items = buildItems(N, kind, labels, defs, opts.origin, opts.fill);
    var lines = ['# NuclearCraft turbine coil plane (' + N + 'x' + N + ')',
                 '# generated by TurbineOpt'];
    for (var i = 0; i < items.length; i++) {
      var it = items[i], b = it.block;
      var cmd = 'setblock ' + it.pos[0] + ' ' + it.pos[1] + ' ' + it.pos[2] + ' ' + b.Name;
      if (b.meta != null) cmd += ' ' + b.meta;
      lines.push(cmd);
    }
    return lines.join('\n') + '\n';
  }

  // --- Building Gadgets SNBT ---------------------------------------------
  function blockStateSnbt(b) {
    var s = '{Name:"' + b.Name + '"';
    if (b.Properties) {
      var keys = Object.keys(b.Properties);
      if (keys.length) {
        s += ',Properties:{';
        for (var i = 0; i < keys.length; i++) {
          if (i) s += ',';
          s += keys[i] + ':"' + b.Properties[keys[i]] + '"';
        }
        s += '}';
      }
    }
    return s + '}';
  }

  function toBuildingGadgets(N, kind, labels, defs, opts) {
    opts = opts || {};
    var origin = opts.origin || [0, 0, 0];
    var items = buildItems(N, kind, labels, defs, origin, opts.fill);

    // Assign a palette slot to every distinct block state.
    var slotOf = {}, palette = [];
    var posInts = [], stateInts = [];
    for (var i = 0; i < items.length; i++) {
      var it = items[i], key = blockStateSnbt(it.block);
      var slot = slotOf[key];
      if (slot == null) { slot = palette.length; slotOf[key] = slot; palette.push(it.block); }
      var dx = it.pos[0] - origin[0], dy = it.pos[1] - origin[1], dz = it.pos[2] - origin[2];
      posInts.push(((dx & 0xff) << 16) | ((dy & 0xff) << 8) | (dz & 0xff));
      stateInts.push(slot);
    }

    var s = '{';
    s += 'startPos:{X:' + origin[0] + ',Y:' + origin[1] + ',Z:' + origin[2] + '},';
    s += 'endPos:{X:' + (origin[0] + N - 1) + ',Y:' + (origin[1] + N - 1) + ',Z:' + origin[2] + '},';
    s += 'posIntArray:[I;' + posInts.join(',') + '],';
    s += 'stateIntArray:[I;' + stateInts.join(',') + '],';
    s += 'mapIntState:[';
    for (i = 0; i < palette.length; i++) {
      if (i) s += ',';
      s += '{mapSlot:' + i + 's,mapState:' + blockStateSnbt(palette[i]) + '}';
    }
    s += ']}';
    return s;
  }

  // --- vanilla structure .nbt --------------------------------------------
  // Structure coordinates are always local (0..N-1); the world origin only
  // matters for /setblock and the Building Gadgets template.
  function toStructureTag(N, kind, labels, defs, opts) {
    var items = buildItems(N, kind, labels, defs, [0, 0, 0], (opts && opts.fill));

    var palette = [], slotOf = {};
    var blocks = [];
    for (var i = 0; i < items.length; i++) {
      var it = items[i], key = blockStateSnbt(it.block);
      var slot = slotOf[key];
      if (slot == null) { slot = palette.length; slotOf[key] = slot; palette.push(it.block); }
      var entries = {};
      // 1.12.2 uses TAG_List of TAG_Int for both pos and size (not int arrays).
      entries.pos = Nbt.list(Nbt.T.INT, [Nbt.int(it.pos[0]), Nbt.int(it.pos[1]), Nbt.int(it.pos[2])]);
      entries.state = Nbt.int(slot);
      blocks.push(Nbt.compound(entries));
    }
    var paletteTags = palette.map(function (b) {
      var e = { Name: Nbt.string(b.Name) };
      if (b.Properties) {
        var props = {};
        Object.keys(b.Properties).forEach(function (k) { props[k] = Nbt.string(b.Properties[k]); });
        e.Properties = Nbt.compound(props);
      }
      return Nbt.compound(e);
    });

    return Nbt.compound({
      author: Nbt.string('TurbineOpt'),
      size: Nbt.list(Nbt.T.INT, [Nbt.int(N), Nbt.int(N), Nbt.int(1)]),
      palette: Nbt.list(Nbt.T.COMPOUND, paletteTags),
      blocks: Nbt.list(Nbt.T.COMPOUND, blocks),
      entities: Nbt.list(Nbt.T.END, []),
      DataVersion: Nbt.int(1343)
    });
  }

  function download(filename, data, mime) {
    var blob = (data instanceof Uint8Array)
      ? new Blob([data], { type: mime || 'application/octet-stream' })
      : new Blob([data], { type: mime || 'text/plain;charset=utf-8' });
    var url = URL.createObjectURL(blob);
    var a = document.createElement('a');
    a.href = url; a.download = filename;
    document.body.appendChild(a); a.click();
    document.body.removeChild(a);
    setTimeout(function () { URL.revokeObjectURL(url); }, 1000);
  }

  var api = {
    BASE_META: BASE_META,
    buildItems: buildItems,
    toMcFunction: toMcFunction,
    toBuildingGadgets: toBuildingGadgets,
    toStructureTag: toStructureTag,
    download: download
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.TurbineExport = api;
})(typeof window !== 'undefined' ? window : globalThis);
